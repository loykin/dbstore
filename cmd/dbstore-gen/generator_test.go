func TestRenderComplianceFiles_SeparateApplicationAndGeneratedOwnership(t *testing.T) {
	iface, err := parseInterface(fixtureFile, "UserRepository")
	if err != nil {
		t.Fatal(err)
	}
	view := buildView(iface, []Backend{{
		Name:       "sqlite",
		ImportPath: "github.com/loykin/dbstore/adapters/sqlx",
		PkgName:    "sqlxadapter",
	}})

	suite, err := renderComplianceSuiteSkeleton(view)
	if err != nil {
		t.Fatal(err)
	}
	content := string(suite)
	for _, want := range []string{
		"type userRepoCapabilities struct{}",
		"caps userRepoCapabilities",
	} {
		if !strings.Contains(content, want) {
			t.Errorf("suite skeleton missing %q\n---\n%s", want, content)
		}
	}
	if strings.Contains(content, "sqliteUserFixture") {
		t.Error("application-owned suite must not own the generated backend registry")
	}

	fixture, err := renderFixtureStub(view, view.Backends[0])
	if err != nil {
		t.Fatal(err)
	}
	fixtureContent := string(fixture)
	for _, want := range []string{
		"var sqliteUserFixture = dbstoretest.Fixture[UserRepository, userRepoCapabilities]",
		`panic("TODO: construct sqlite UserRepository")`,
	} {
		if !strings.Contains(fixtureContent, want) {
			t.Errorf("fixture skeleton missing %q\n---\n%s", want, fixtureContent)
		}
	}

	registry, err := renderComplianceRegistry(view)
	if err != nil {
		t.Fatal(err)
	}
	registryContent := string(registry)
	for _, want := range []string{
		"// Code generated by dbstore-gen. DO NOT EDIT.",
		"dbstoretest.Fixture[UserRepository, userRepoCapabilities]",
		"sqliteUserFixture",
	} {
		if !strings.Contains(registryContent, want) {
			t.Errorf("generated registry missing %q\n---\n%s", want, registryContent)
		}
	}
}
