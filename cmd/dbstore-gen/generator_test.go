func TestRenderGenFile_ProducesValidGoWithExpectedShape(t *testing.T) {
	iface, err := parseInterface(fixtureFile, "UserRepository")
	if err != nil {
		t.Fatal(err)
	}
	backends := []Backend{
		{Name: "sqlite", ImportPath: "github.com/loykin/dbstore/adapters/sqlx", PkgName: "sqlxadapter"},
	}
	view := buildView(iface, backends)

	out, err := renderGenFile(view)
	if err != nil {
		t.Fatal(err)
	}
	content := string(out)

	for _, want := range []string{
		"// Code generated by dbstore-gen. DO NOT EDIT.",
		"type UserRepoBackend[A any] interface {",
		"type userRepo[A any] struct {",
		"\tbackend UserRepoBackend[A]",
		"\tsrc     dbstore.Runner[A]",
		"func NewUserRepo[A any](backend UserRepoBackend[A], src dbstore.Runner[A]) UserRepository {",
		"func (r *userRepo[A]) FindByID(ctx context.Context, id int) (*User, error) {",
		"return dbstore.Call(ctx, r.src, func(ctx context.Context, a A) (*User, error) {",
		"var _ UserRepoBackend[sqlxadapter.Handle] = SqliteUserBackend{}",
	} {
		if !strings.Contains(content, want) {
			t.Errorf("generated file missing %q\n---\n%s", want, content)
		}
	}
	// src must never be an anonymous embed — the one structural guarantee
	// this generator exists to preserve.
	if strings.Contains(content, "\tdbstore.Runner[A]\n") {
		t.Error("src must be a named field, never an anonymous embed")
	}
}

